`timescale 1ns/1ps

// -----------------------------------------------------------------------------
// render_cmd_mem_engine
// -----------------------------------------------------------------------------
// Vendor-neutral command mover.  By default it retains the original
// single-beat request path.  Setting WRITE_BURST_ENABLE enables the line
// write-back path; setting READ_BURST_ENABLE additionally fetches complete
// source/background rows through bounded read descriptors.  The same
// dual-port line RAM first holds the source row and is then overwritten with
// the Alpha/Color-Key result, avoiding a second full-line buffer.
//
// The one-outstanding-request policy is retained for reads.  A write descriptor
// is accepted before its data beats are presented, which lets an owner-aware
// arbiter hold the write-data owner until mem_wr_last.
//
// Supported operations:
//   NOP          : no request, immediate completion;
//   SOLID_FILL   : constant line write (no source reads);
//   BLOCK_COPY   : source row reads followed by a line write;
//   COLOR_KEY    : source/background row reads followed by a line write;
//   ALPHA_BLEND  : source/background row reads + RGB565 blend + line write.
//
// Addresses are byte addresses.  The engine advances by two bytes per pixel
// and applies each descriptor's byte stride at the end of a row.  Invalid
// descriptors are completed with `done_error` and never issue a request; this
// protects users that bypass render_cmd_parser in a unit test.
// -----------------------------------------------------------------------------
module render_cmd_mem_engine #(
    parameter int ADDR_W = 32,
    parameter int DATA_W = 16,
    parameter int LEN_W  = 16,
    parameter int SEQ_W  = 32,
    // Keep the legacy path as the default so existing command/memory TBs can
    // omit the new write-data ports.  Board integration should set this to 1.
    parameter bit WRITE_BURST_ENABLE = 1'b0,
    // READ_BURST_ENABLE requires WRITE_BURST_ENABLE.  It is kept off by
    // default solely for backwards-compatible unit tests; the system wrapper
    // enables both paths for the competition architecture.
    parameter bit READ_BURST_ENABLE = 1'b0,
    parameter int MAX_READ_BEATS = 16,
    parameter int MAX_WRITE_BEATS = 16,
    parameter int LINE_BUFFER_PIXELS = 4096,
    parameter int READ_BOUNDARY_BYTES = 4096,
    // No abstract write descriptor may cross this boundary.  4096 maps
    // directly to AXI's mandatory 4 KiB burst rule.
    parameter int WRITE_BOUNDARY_BYTES = 4096
) (
    input  logic                 clk,
    input  logic                 rst_n,

    input  logic                 desc_valid,
    output logic                 desc_ready,
    input  logic [SEQ_W-1:0]     desc_seq,
    input  logic [2:0]           desc_op,
    input  logic [7:0]           desc_flags,
    input  logic [1:0]           desc_pixel_fmt,
    input  logic [ADDR_W-1:0]    desc_src_addr,
    input  logic [ADDR_W-1:0]    desc_dst_addr,
    input  logic [15:0]          desc_width,
    input  logic [15:0]          desc_height,
    input  logic [15:0]          desc_src_stride_bytes,
    input  logic [15:0]          desc_dst_stride_bytes,
    input  logic [31:0]          desc_color,
    input  logic [7:0]           desc_alpha,
    input  logic [15:0]          desc_color_key,

    output logic                 mem_req_valid,
    input  logic                 mem_req_ready,
    output logic                 mem_req_write,
    output logic [ADDR_W-1:0]    mem_req_addr,
    output logic [LEN_W-1:0]     mem_req_len,
    output logic [DATA_W-1:0]    mem_req_wdata,
    output logic [(DATA_W/8)-1:0] mem_req_wstrb,

    input  logic                 mem_rsp_valid,
    output logic                 mem_rsp_ready,
    input  logic [DATA_W-1:0]    mem_rsp_rdata,
    input  logic                 mem_rsp_last,
    input  logic                 mem_rsp_error,

    // Burst write-data channel.  A descriptor handshake on mem_req_* always
    // precedes the first beat.  `mem_wr_last` is generated by this engine and
    // must be preserved by the owner-aware arbiter while back-pressured.
    output logic                 mem_wr_valid,
    input  logic                 mem_wr_ready,
    output logic [DATA_W-1:0]    mem_wr_data,
    output logic [(DATA_W/8)-1:0] mem_wr_strb,
    output logic                 mem_wr_last,
    input  logic                 mem_wr_error,

    // Completion response for the accepted write descriptor.  `done_valid`
    // is not asserted until this response is consumed.
    input  logic                 mem_wr_rsp_valid,
    output logic                 mem_wr_rsp_ready,
    input  logic                 mem_wr_rsp_error,

    output logic                 done_valid,
    output logic                 done_error,
    output logic [SEQ_W-1:0]     done_seq,
    output logic                 busy,
    output logic [31:0]          request_count,
    output logic [31:0]          read_count,
    output logic [31:0]          write_count,
    output logic [31:0]          pixel_count,
    output logic [31:0]          error_count
);

    localparam logic [2:0] OP_NOP_C         = 3'd0;
    localparam logic [2:0] OP_SOLID_FILL_C  = 3'd1;
    localparam logic [2:0] OP_BLOCK_COPY_C  = 3'd2;
    localparam logic [2:0] OP_ALPHA_BLEND_C = 3'd3;
    localparam logic [2:0] OP_COLOR_KEY_C   = 3'd4;
    localparam logic [1:0] PIXEL_FMT_RGB565_C = 2'd0;

    typedef enum logic [4:0] {
        ST_IDLE,
        ST_FILL_WRITE,
        ST_READ_SRC_REQ,
        ST_READ_SRC_WAIT,
        ST_READ_DST_REQ,
        ST_READ_DST_WAIT,
        ST_WRITE_RESULT,
        ST_LINE_READ_SRC_REQ,
        ST_LINE_READ_SRC_DATA,
        ST_LINE_READ_DST_REQ,
        ST_LINE_READ_DST_DATA,
        ST_LINE_READ_DST_DRAIN,
        ST_LINE_WRITE_REQ,
        ST_LINE_WRITE_DATA,
        ST_LINE_WRITE_RSP
    } state_e;

    state_e state;

    logic [SEQ_W-1:0]  seq_reg;
    logic [2:0]        op_reg;
    logic [7:0]        flags_reg;
    logic [1:0]        pixel_fmt_reg;
    logic [ADDR_W-1:0] src_addr_reg;
    logic [ADDR_W-1:0] dst_addr_reg;
    logic [15:0]       width_reg;
    logic [15:0]       height_reg;
    logic [15:0]       src_stride_reg;
    logic [15:0]       dst_stride_reg;
    logic [31:0]       color_reg;
    logic [7:0]        alpha_reg;
    logic [15:0]       color_key_reg;

    logic [15:0]       x_reg;
    logic [15:0]       y_reg;
    logic [ADDR_W-1:0] cur_src_addr;
    logic [ADDR_W-1:0] cur_dst_addr;
    // Row bases are independent of the legacy per-pixel address registers.
    // The burst path advances them only after a complete row is committed.
    logic [ADDR_W-1:0] row_src_base_reg;
    logic [ADDR_W-1:0] row_dst_base_reg;
    logic [DATA_W-1:0] src_pixel_reg;
    logic [DATA_W-1:0] dst_pixel_reg;

    localparam int BYTE_LANES = DATA_W / 8;
    localparam int LINE_BUF_DEPTH = (LINE_BUFFER_PIXELS < 1) ? 1 :
                                    LINE_BUFFER_PIXELS;
    localparam int LINE_BUF_ADDR_W = (LINE_BUF_DEPTH <= 1) ? 1 :
                                     $clog2(LINE_BUF_DEPTH);
    logic [DATA_W-1:0] line_buf [0:LINE_BUF_DEPTH-1];
    logic [DATA_W-1:0] line_buf_rd_q;
    logic              line_buf_wr_en;
    logic [LINE_BUF_ADDR_W-1:0] line_buf_wr_addr;
    logic [DATA_W-1:0] line_buf_wr_data;
    logic              line_buf_rd_en;
    logic [LINE_BUF_ADDR_W-1:0] line_buf_rd_addr;
    logic [15:0]       line_write_index;
    logic [15:0]       segment_beat_index;
    logic [15:0]       segment_beats_reg;
    logic              burst_error_seen;

    logic [15:0]       line_read_index;
    logic [15:0]       read_segment_beat_index;
    logic [15:0]       read_segment_beats_reg;
    logic              dst_pipe_valid_q;
    logic [DATA_W-1:0] dst_pipe_data_q;
    logic [LINE_BUF_ADDR_W-1:0] dst_pipe_index_q;

    logic [ADDR_W-1:0] src_row_step;
    logic [ADDR_W-1:0] dst_row_step;
    logic [ADDR_W-1:0] next_src_addr;
    logic [ADDR_W-1:0] next_dst_addr;
    logic [15:0]       next_x;
    logic [15:0]       next_y;
    logic              last_pixel;
    logic              desc_fire;
    logic              req_fire;
    logic              rsp_fire;
    logic              wr_fire;
    logic              wr_rsp_fire;
    logic [16:0]       segment_remaining;
    logic [16:0]       segment_end_index;
    logic [15:0]       segment_beats_calc;
    logic [ADDR_W-1:0] segment_addr_calc;
    logic [ADDR_W-1:0] segment_boundary_offset;
    logic [16:0]       boundary_beats_calc;
    logic [16:0]       segment_limit_calc;
    logic [16:0]       read_segment_remaining;
    logic [16:0]       read_segment_end_index;
    logic [15:0]       read_segment_beats_calc;
    logic [ADDR_W-1:0] read_segment_addr_calc;
    logic [ADDR_W-1:0] read_segment_base_calc;
    logic [ADDR_W-1:0] read_boundary_offset;
    logic [16:0]       read_boundary_beats_calc;
    logic [16:0]       read_segment_limit_calc;
    logic              read_rsp_expected_last;
    logic              read_rsp_protocol_ok;
    logic              direct_desc_bad;
    logic              direct_desc_bad_op;

    // One pixel is two bytes.  Row step is the distance from the current
    // (last) pixel to the first pixel in the next row.
    always_comb begin
        // Sized casts keep the arithmetic well-defined for every supported
        // address width; the earlier concatenation form accidentally made
        // the stride operand one bit narrower when ADDR_W=32.
        src_row_step = ADDR_W'(src_stride_reg) -
                       (ADDR_W'(width_reg) << 1) + ADDR_W'(2);
        dst_row_step = ADDR_W'(dst_stride_reg) -
                       (ADDR_W'(width_reg) << 1) + ADDR_W'(2);

        last_pixel = (x_reg == (width_reg - 16'd1)) &&
                     (y_reg == (height_reg - 16'd1));
        if (x_reg == (width_reg - 16'd1)) begin
            next_x       = 16'd0;
            next_y       = y_reg + 16'd1;
            next_src_addr = cur_src_addr + src_row_step;
            next_dst_addr = cur_dst_addr + dst_row_step;
        end else begin
            next_x       = x_reg + 16'd1;
            next_y       = y_reg;
            next_src_addr = cur_src_addr + {{(ADDR_W-2){1'b0}}, 2'd2};
            next_dst_addr = cur_dst_addr + {{(ADDR_W-2){1'b0}}, 2'd2};
        end

        // Split a long row into bounded descriptors.  The index is kept at
        // 16 bits because command widths are 16 bits; the extra bit on the
        // subtraction prevents an underflow from wrapping a malformed state.
        if (width_reg > line_write_index)
            segment_remaining = {1'b0, width_reg} -
                                {1'b0, line_write_index};
        else
            segment_remaining = 17'd0;
        segment_addr_calc = row_dst_base_reg +
                            (ADDR_W'(line_write_index) *
                             ADDR_W'(BYTE_LANES));
        segment_boundary_offset = segment_addr_calc % WRITE_BOUNDARY_BYTES;
        boundary_beats_calc = 17'(
            (WRITE_BOUNDARY_BYTES - segment_boundary_offset) / BYTE_LANES);

        segment_limit_calc = segment_remaining;
        if (segment_limit_calc > MAX_WRITE_BEATS)
            segment_limit_calc = MAX_WRITE_BEATS;
        if (segment_limit_calc > boundary_beats_calc)
            segment_limit_calc = boundary_beats_calc;
        segment_beats_calc = segment_limit_calc[15:0];
        segment_end_index = {1'b0, line_write_index} +
                            {1'b0, segment_beats_reg};

        // The source and destination row readers use the same segmentation
        // rule as the writer: cap the descriptor length and never cross an
        // AXI 4 KiB boundary.  Addresses and lengths remain expressed in the
        // abstract port's DATA_W beats.
        if ((state == ST_LINE_READ_DST_REQ) ||
            (state == ST_LINE_READ_DST_DATA) ||
            (state == ST_LINE_READ_DST_DRAIN))
            read_segment_base_calc = row_dst_base_reg;
        else
            read_segment_base_calc = row_src_base_reg;

        if (width_reg > line_read_index)
            read_segment_remaining = {1'b0, width_reg} -
                                     {1'b0, line_read_index};
        else
            read_segment_remaining = 17'd0;
        read_segment_addr_calc = read_segment_base_calc +
                                 (ADDR_W'(line_read_index) *
                                  ADDR_W'(BYTE_LANES));
        read_boundary_offset = read_segment_addr_calc % READ_BOUNDARY_BYTES;
        read_boundary_beats_calc = 17'(
            (READ_BOUNDARY_BYTES - read_boundary_offset) / BYTE_LANES);
        read_segment_limit_calc = read_segment_remaining;
        if (read_segment_limit_calc > MAX_READ_BEATS)
            read_segment_limit_calc = MAX_READ_BEATS;
        if (read_segment_limit_calc > read_boundary_beats_calc)
            read_segment_limit_calc = read_boundary_beats_calc;
        read_segment_beats_calc = read_segment_limit_calc[15:0];
        read_segment_end_index = {1'b0, line_read_index} +
                                 {1'b0, read_segment_beats_reg};
        read_rsp_expected_last =
            (read_segment_beat_index == (read_segment_beats_reg - 16'd1));
        read_rsp_protocol_ok = !mem_rsp_error &&
                               (mem_rsp_last == read_rsp_expected_last);
    end

    // RGB565 blend with round-to-nearest and saturation.  Integer arithmetic
    // here is a simulation-friendly reference implementation; a later timing
    // build may replace the /255 constants with multiply/shift or a LUT.
    function automatic [15:0] blend565(
        input logic [15:0] fg,
        input logic [15:0] bg,
        input logic [7:0]  a
    );
        integer fr, fg6, fb, br, bg6, bb;
        integer rr, gg, bb_out;
        logic [4:0] r5;
        logic [5:0] g6;
        logic [4:0] b5;
        begin
            fr  = fg[15:11];
            fg6 = fg[10:5];
            fb  = fg[4:0];
            br  = bg[15:11];
            bg6 = bg[10:5];
            bb  = bg[4:0];
            // Match alpha_blend_pixel.sv: round-to-nearest uses a +128
            // bias for the integer division by 255.
            rr = (fr * a + br * (255 - a) + 128) / 255;
            gg = (fg6 * a + bg6 * (255 - a) + 128) / 255;
            bb_out = (fb * a + bb * (255 - a) + 128) / 255;
            if (rr > 31) rr = 31;
            if (gg > 63) gg = 63;
            if (bb_out > 31) bb_out = 31;
            r5 = 5'(rr);
            g6 = 6'(gg);
            b5 = 5'(bb_out);
            blend565 = {r5, g6, b5};
        end
    endfunction

    always_comb begin
        direct_desc_bad_op = (desc_op > OP_COLOR_KEY_C);
        direct_desc_bad = direct_desc_bad_op ||
                          (desc_pixel_fmt != PIXEL_FMT_RGB565_C) ||
                          ((desc_op != OP_NOP_C) &&
                           ((desc_width == 16'd0) || (desc_height == 16'd0))) ||
                          ((desc_op != OP_NOP_C) && (desc_dst_addr[0])) ||
                          ((desc_op != OP_NOP_C) &&
                           (desc_dst_stride_bytes[0] ||
                            ({1'b0, desc_dst_stride_bytes} <
                             ({1'b0, desc_width} << 1)) ||
                            (((desc_op == OP_BLOCK_COPY_C) ||
                              (desc_op == OP_ALPHA_BLEND_C) ||
                              (desc_op == OP_COLOR_KEY_C)) &&
                             (desc_src_addr[0] ||
                              desc_src_stride_bytes[0] ||
                             ({1'b0, desc_src_stride_bytes} <
                               ({1'b0, desc_width} << 1))))));
        // Match the parser even when a caller bypasses it: every used RGB565
        // stride must preserve two-byte row alignment. NOP uses no surface;
        // SOLID_FILL does not use or validate the source stride/address.
        if ((WRITE_BURST_ENABLE || READ_BURST_ENABLE) &&
            ((desc_op == OP_BLOCK_COPY_C) ||
             (desc_op == OP_ALPHA_BLEND_C) ||
             (desc_op == OP_COLOR_KEY_C)) &&
            (desc_width > LINE_BUFFER_PIXELS))
            direct_desc_bad = 1'b1;
    end

    always_comb begin
        desc_ready = (state == ST_IDLE);
        desc_fire  = desc_valid && desc_ready;

        mem_req_valid = (state == ST_FILL_WRITE) ||
                        (state == ST_READ_SRC_REQ) ||
                        (state == ST_READ_DST_REQ) ||
                        (state == ST_WRITE_RESULT) ||
                        (READ_BURST_ENABLE &&
                         ((state == ST_LINE_READ_SRC_REQ) ||
                          (state == ST_LINE_READ_DST_REQ))) ||
                        (WRITE_BURST_ENABLE && (state == ST_LINE_WRITE_REQ));
        mem_req_write = (state == ST_FILL_WRITE) || (state == ST_WRITE_RESULT);
        mem_req_addr  = cur_dst_addr;
        if ((state == ST_READ_SRC_REQ))
            mem_req_addr = cur_src_addr;
        else if ((state == ST_READ_DST_REQ) || (state == ST_WRITE_RESULT) ||
                 (state == ST_FILL_WRITE))
            mem_req_addr = cur_dst_addr;
        mem_req_len   = '0;
        mem_req_wdata = '0;
        if (state == ST_FILL_WRITE)
            mem_req_wdata = color_reg[DATA_W-1:0];
        else if (state == ST_WRITE_RESULT) begin
            if (op_reg == OP_BLOCK_COPY_C)
                mem_req_wdata = src_pixel_reg;
            else if (op_reg == OP_ALPHA_BLEND_C)
                mem_req_wdata = blend565(src_pixel_reg[15:0],
                                         dst_pixel_reg[15:0], alpha_reg);
            else
                mem_req_wdata = src_pixel_reg;
        end
        mem_req_wstrb = {(DATA_W/8){1'b1}};

        if (READ_BURST_ENABLE &&
            ((state == ST_LINE_READ_SRC_REQ) ||
             (state == ST_LINE_READ_DST_REQ))) begin
            mem_req_write = 1'b0;
            mem_req_addr  = read_segment_addr_calc;
            mem_req_len   = read_segment_beats_calc - 16'd1;
            mem_req_wdata = '0;
            mem_req_wstrb = '0;
        end

        if (WRITE_BURST_ENABLE && (state == ST_LINE_WRITE_REQ)) begin
            mem_req_write = 1'b1;
            // line_write_index is the first pixel of this segment.  The
            // descriptor address is byte based, just like the legacy path.
            mem_req_addr = segment_addr_calc;
            mem_req_len  = segment_beats_calc - 16'd1;
            // Burst payload is carried on mem_wr_*; keep the legacy field
            // zero so an adapter cannot accidentally duplicate beat zero.
            mem_req_wdata = '0;
            mem_req_wstrb = '0;
        end

        mem_wr_valid = WRITE_BURST_ENABLE && (state == ST_LINE_WRITE_DATA);
        mem_wr_data  = '0;
        if (state == ST_LINE_WRITE_DATA) begin
            if (op_reg == OP_SOLID_FILL_C)
                mem_wr_data = color_reg[DATA_W-1:0];
            else
                mem_wr_data = line_buf_rd_q;
        end
        mem_wr_strb = {(DATA_W/8){1'b1}};
        mem_wr_last = (state == ST_LINE_WRITE_DATA) &&
                      (segment_beat_index == (segment_beats_reg - 16'd1));

        mem_rsp_ready = (state == ST_READ_SRC_WAIT) ||
                        (state == ST_READ_DST_WAIT) ||
                        (READ_BURST_ENABLE &&
                         ((state == ST_LINE_READ_SRC_DATA) ||
                          (state == ST_LINE_READ_DST_DATA)));
        req_fire = mem_req_valid && mem_req_ready;
        rsp_fire = mem_rsp_valid && mem_rsp_ready;
        wr_fire  = mem_wr_valid && mem_wr_ready;
        mem_wr_rsp_ready = WRITE_BURST_ENABLE &&
                           (state == ST_LINE_WRITE_RSP);
        wr_rsp_fire = mem_wr_rsp_valid && mem_wr_rsp_ready;
        busy = (state != ST_IDLE);

        // Keep all memory-array access in a reset-free clocked process below.
        // Placing the RAM accesses inside the asynchronous-reset state process
        // prevents both Vivado and typical FPGA tools from inferring block RAM.
        line_buf_wr_en   = 1'b0;
        line_buf_wr_addr = LINE_BUF_ADDR_W'(x_reg);
        line_buf_wr_data = mem_rsp_rdata;
        if (WRITE_BURST_ENABLE && rsp_fire && !mem_rsp_error && mem_rsp_last) begin
            if ((state == ST_READ_SRC_WAIT) &&
                (op_reg != OP_ALPHA_BLEND_C) &&
                !((op_reg == OP_COLOR_KEY_C) &&
                  (mem_rsp_rdata[15:0] == color_key_reg))) begin
                line_buf_wr_en = 1'b1;
            end else if (state == ST_READ_DST_WAIT) begin
                line_buf_wr_en = 1'b1;
                if (op_reg == OP_ALPHA_BLEND_C)
                    line_buf_wr_data = blend565(src_pixel_reg[15:0],
                                                mem_rsp_rdata[15:0],
                                                alpha_reg);
            end
        end
        if (READ_BURST_ENABLE && rsp_fire && read_rsp_protocol_ok &&
            (state == ST_LINE_READ_SRC_DATA)) begin
            line_buf_wr_en = 1'b1;
            line_buf_wr_addr = LINE_BUF_ADDR_W'(
                line_read_index + read_segment_beat_index);
            line_buf_wr_data = mem_rsp_rdata;
        end
        if (READ_BURST_ENABLE && dst_pipe_valid_q) begin
            line_buf_wr_en   = 1'b1;
            line_buf_wr_addr = dst_pipe_index_q;
            if (op_reg == OP_ALPHA_BLEND_C)
                line_buf_wr_data = blend565(line_buf_rd_q[15:0],
                                            dst_pipe_data_q[15:0],
                                            alpha_reg);
            else if (op_reg == OP_COLOR_KEY_C)
                line_buf_wr_data =
                    (line_buf_rd_q[15:0] == color_key_reg) ?
                    dst_pipe_data_q : line_buf_rd_q;
            else
                line_buf_wr_data = dst_pipe_data_q;
        end

        line_buf_rd_en   = 1'b0;
        line_buf_rd_addr = LINE_BUF_ADDR_W'(line_write_index);
        if (READ_BURST_ENABLE && rsp_fire && read_rsp_protocol_ok &&
            (state == ST_LINE_READ_DST_DATA)) begin
            // Read the source pixel in parallel with accepting the matching
            // background beat.  dst_pipe_* holds that beat for one cycle;
            // the RAM output is then overwritten with the computed result.
            line_buf_rd_en = 1'b1;
            line_buf_rd_addr = LINE_BUF_ADDR_W'(
                line_read_index + read_segment_beat_index);
        end else if (WRITE_BURST_ENABLE &&
            (state == ST_LINE_WRITE_REQ) && req_fire &&
            (op_reg != OP_SOLID_FILL_C)) begin
            line_buf_rd_en = 1'b1;
        end else if (WRITE_BURST_ENABLE &&
                     (state == ST_LINE_WRITE_DATA) && wr_fire &&
                     (mem_wr_error !== 1'b1) &&
                     (segment_beat_index != (segment_beats_reg - 16'd1)) &&
                     (op_reg != OP_SOLID_FILL_C)) begin
            line_buf_rd_en = 1'b1;
            line_buf_rd_addr = LINE_BUF_ADDR_W'(
                line_write_index + segment_beat_index + 16'd1);
        end
    end

    // Simple dual-port synchronous RAM: one optional write and one optional
    // registered read per clock. The array and its output register are not
    // reset; validity is controlled entirely by the state machine, and every
    // non-solid line location is written before it is read for writeback.
    always_ff @(posedge clk) begin
        if (line_buf_wr_en)
            line_buf[line_buf_wr_addr] <= line_buf_wr_data;
        if (line_buf_rd_en)
            line_buf_rd_q <= line_buf[line_buf_rd_addr];
    end

    always_ff @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            state         <= ST_IDLE;
            seq_reg       <= '0;
            op_reg        <= OP_NOP_C;
            flags_reg     <= '0;
            pixel_fmt_reg <= PIXEL_FMT_RGB565_C;
            src_addr_reg  <= '0;
            dst_addr_reg  <= '0;
            width_reg     <= '0;
            height_reg    <= '0;
            src_stride_reg <= '0;
            dst_stride_reg <= '0;
            color_reg     <= '0;
            alpha_reg     <= '0;
            color_key_reg <= '0;
            x_reg         <= '0;
            y_reg         <= '0;
            cur_src_addr  <= '0;
            cur_dst_addr  <= '0;
            row_src_base_reg <= '0;
            row_dst_base_reg <= '0;
            src_pixel_reg <= '0;
            dst_pixel_reg <= '0;
            line_write_index <= '0;
            segment_beat_index <= '0;
            segment_beats_reg <= '0;
            burst_error_seen <= 1'b0;
            line_read_index <= '0;
            read_segment_beat_index <= '0;
            read_segment_beats_reg <= '0;
            dst_pipe_valid_q <= 1'b0;
            dst_pipe_data_q <= '0;
            dst_pipe_index_q <= '0;
            done_valid    <= 1'b0;
            done_error    <= 1'b0;
            done_seq      <= '0;
            request_count <= 32'd0;
            read_count    <= 32'd0;
            write_count   <= 32'd0;
            pixel_count   <= 32'd0;
            error_count   <= 32'd0;
        end else begin
            done_valid <= 1'b0;
            done_error <= 1'b0;
            // A destination response and the corresponding synchronous RAM
            // read form a one-stage pipeline.  The valid flag is a pulse; the
            // combinational RAM-write controls consume it in the next cycle.
            dst_pipe_valid_q <= 1'b0;
            if (READ_BURST_ENABLE && dst_pipe_valid_q)
                pixel_count <= pixel_count + 32'd1;

            if (desc_fire) begin
                seq_reg        <= desc_seq;
                op_reg         <= desc_op;
                flags_reg      <= desc_flags;
                pixel_fmt_reg  <= desc_pixel_fmt;
                src_addr_reg   <= desc_src_addr;
                dst_addr_reg   <= desc_dst_addr;
                width_reg      <= desc_width;
                height_reg     <= desc_height;
                src_stride_reg <= desc_src_stride_bytes;
                dst_stride_reg <= desc_dst_stride_bytes;
                color_reg      <= desc_color;
                alpha_reg      <= desc_alpha;
                color_key_reg  <= desc_color_key;
                x_reg          <= 16'd0;
                y_reg          <= 16'd0;
                cur_src_addr   <= desc_src_addr;
                cur_dst_addr   <= desc_dst_addr;
                row_src_base_reg <= desc_src_addr;
                row_dst_base_reg <= desc_dst_addr;
                line_write_index <= 16'd0;
                segment_beat_index <= 16'd0;
                segment_beats_reg <= 16'd0;
                burst_error_seen <= 1'b0;
                line_read_index <= 16'd0;
                read_segment_beat_index <= 16'd0;
                read_segment_beats_reg <= 16'd0;
                dst_pipe_valid_q <= 1'b0;

                if (direct_desc_bad) begin
                    done_valid <= 1'b1;
                    done_error <= 1'b1;
                    done_seq   <= desc_seq;
                    error_count <= error_count + 32'd1;
                    state <= ST_IDLE;
                end else if (desc_op == OP_NOP_C) begin
                    done_valid <= 1'b1;
                    done_error <= 1'b0;
                    done_seq   <= desc_seq;
                    state <= ST_IDLE;
                end else if (desc_op == OP_SOLID_FILL_C) begin
                    if (WRITE_BURST_ENABLE)
                        state <= ST_LINE_WRITE_REQ;
                    else
                        state <= ST_FILL_WRITE;
                end else begin
                    if (READ_BURST_ENABLE)
                        state <= ST_LINE_READ_SRC_REQ;
                    else
                        state <= ST_READ_SRC_REQ;
                end
            // A burst read descriptor is accepted before any response beat.
            // Only one descriptor is outstanding, which matches the owner
            // contract of c2_mem_arbiter_2m_owner.
            end else if (READ_BURST_ENABLE && req_fire &&
                         ((state == ST_LINE_READ_SRC_REQ) ||
                          (state == ST_LINE_READ_DST_REQ))) begin
                request_count <= request_count + 32'd1;
                read_count <= read_count + 32'd1;
                read_segment_beats_reg <= read_segment_beats_calc;
                read_segment_beat_index <= 16'd0;
                if (state == ST_LINE_READ_SRC_REQ)
                    state <= ST_LINE_READ_SRC_DATA;
                else
                    state <= ST_LINE_READ_DST_DATA;
            end else if (READ_BURST_ENABLE && rsp_fire &&
                         (state == ST_LINE_READ_SRC_DATA)) begin
                if (!read_rsp_protocol_ok) begin
                    done_valid <= 1'b1;
                    done_error <= 1'b1;
                    done_seq <= seq_reg;
                    error_count <= error_count + 32'd1;
                    state <= ST_IDLE;
                end else begin
                    if (op_reg == OP_BLOCK_COPY_C)
                        pixel_count <= pixel_count + 32'd1;
                    if (read_rsp_expected_last) begin
                        if (read_segment_end_index >= {1'b0, width_reg}) begin
                            line_read_index <= 16'd0;
                            line_write_index <= 16'd0;
                            if (op_reg == OP_BLOCK_COPY_C)
                                state <= ST_LINE_WRITE_REQ;
                            else
                                state <= ST_LINE_READ_DST_REQ;
                        end else begin
                            line_read_index <= line_read_index +
                                               read_segment_beats_reg;
                            state <= ST_LINE_READ_SRC_REQ;
                        end
                    end else begin
                        read_segment_beat_index <=
                            read_segment_beat_index + 16'd1;
                    end
                end
            end else if (READ_BURST_ENABLE && rsp_fire &&
                         (state == ST_LINE_READ_DST_DATA)) begin
                if (!read_rsp_protocol_ok) begin
                    done_valid <= 1'b1;
                    done_error <= 1'b1;
                    done_seq <= seq_reg;
                    error_count <= error_count + 32'd1;
                    state <= ST_IDLE;
                end else begin
                    dst_pipe_valid_q <= 1'b1;
                    dst_pipe_data_q <= mem_rsp_rdata;
                    dst_pipe_index_q <= LINE_BUF_ADDR_W'(
                        line_read_index + read_segment_beat_index);
                    if (read_rsp_expected_last)
                        state <= ST_LINE_READ_DST_DRAIN;
                    else
                        read_segment_beat_index <=
                            read_segment_beat_index + 16'd1;
                end
            end else if (READ_BURST_ENABLE &&
                         (state == ST_LINE_READ_DST_DRAIN)) begin
                // The last destination beat is written to line_buf on this
                // edge.  Do not prefetch write beat zero until the next state.
                if (read_segment_end_index >= {1'b0, width_reg}) begin
                    line_read_index <= 16'd0;
                    line_write_index <= 16'd0;
                    state <= ST_LINE_WRITE_REQ;
                end else begin
                    line_read_index <= line_read_index +
                                       read_segment_beats_reg;
                    state <= ST_LINE_READ_DST_REQ;
                end
            // A burst descriptor is a separate phase from its write data.
            // This branch is intentionally before the legacy req_fire branch:
            // otherwise a line descriptor would be mistaken for a completed
            // single-pixel write.
            end else if (WRITE_BURST_ENABLE &&
                         (state == ST_LINE_WRITE_REQ) && req_fire) begin
                request_count      <= request_count + 32'd1;
                write_count        <= write_count + 32'd1;
                segment_beats_reg  <= segment_beats_calc;
                segment_beat_index <= 16'd0;
                burst_error_seen   <= 1'b0;
                // Synchronous line-buffer read.  The descriptor phase is the
                // prefetch cycle for beat zero; subsequent reads advance only
                // on accepted write beats, so data remains stable under
                // back-pressure and maps cleanly to block RAM.
                state              <= ST_LINE_WRITE_DATA;
            end else if (WRITE_BURST_ENABLE &&
                         (state == ST_LINE_WRITE_DATA) && wr_fire) begin
                // Pixel count means processed pixels.  Non-solid operations
                // count while filling the line buffer; solid fill counts as
                // its generated beats enter the memory adapter.
                if (op_reg == OP_SOLID_FILL_C)
                    pixel_count <= pixel_count + 32'd1;

                if (mem_wr_error === 1'b1)
                    burst_error_seen <= 1'b1;

                if ((mem_wr_error === 1'b1) ||
                    (segment_beat_index == (segment_beats_reg - 16'd1))) begin
                    // The data phase is not completion.  Wait for the later
                    // controller commit/error response (AXI B equivalent).
                    state <= ST_LINE_WRITE_RSP;
                end else begin
                    segment_beat_index <= segment_beat_index + 16'd1;
                end
            end else if (WRITE_BURST_ENABLE &&
                         (state == ST_LINE_WRITE_RSP) && wr_rsp_fire) begin
                if (burst_error_seen ||
                    (mem_wr_rsp_error === 1'b1)) begin
                    done_valid  <= 1'b1;
                    done_error  <= 1'b1;
                    done_seq    <= seq_reg;
                    error_count <= error_count + 32'd1;
                    state       <= ST_IDLE;
                end else if (segment_end_index >= {1'b0, width_reg}) begin
                    // The row is committed.  Start the next row, or complete
                    // the command when the final row response succeeds.
                    if (y_reg == (height_reg - 16'd1)) begin
                        done_valid <= 1'b1;
                        done_error <= 1'b0;
                        done_seq   <= seq_reg;
                        state      <= ST_IDLE;
                    end else begin
                        y_reg <= y_reg + 16'd1;
                        x_reg <= 16'd0;
                        if (READ_BURST_ENABLE &&
                            (op_reg != OP_SOLID_FILL_C)) begin
                            row_src_base_reg <= row_src_base_reg +
                                                ADDR_W'(src_stride_reg);
                            row_dst_base_reg <= row_dst_base_reg +
                                                ADDR_W'(dst_stride_reg);
                            cur_src_addr <= row_src_base_reg +
                                            ADDR_W'(src_stride_reg);
                            cur_dst_addr <= row_dst_base_reg +
                                            ADDR_W'(dst_stride_reg);
                            line_read_index <= 16'd0;
                            read_segment_beat_index <= 16'd0;
                            read_segment_beats_reg <= 16'd0;
                        end else if (op_reg == OP_SOLID_FILL_C) begin
                            cur_src_addr <= cur_src_addr +
                                            ADDR_W'(src_stride_reg);
                            cur_dst_addr <= row_dst_base_reg +
                                            ADDR_W'(dst_stride_reg);
                        end else begin
                            cur_src_addr <= cur_src_addr + src_row_step;
                            cur_dst_addr <= cur_dst_addr + dst_row_step;
                        end
                        if (!(READ_BURST_ENABLE &&
                              (op_reg != OP_SOLID_FILL_C))) begin
                            row_src_base_reg <= row_src_base_reg +
                                                ADDR_W'(src_stride_reg);
                            row_dst_base_reg <= row_dst_base_reg +
                                                ADDR_W'(dst_stride_reg);
                        end
                        line_write_index <= 16'd0;
                        if (op_reg == OP_SOLID_FILL_C)
                            state <= ST_LINE_WRITE_REQ;
                        else if (READ_BURST_ENABLE)
                            state <= ST_LINE_READ_SRC_REQ;
                        else
                            state <= ST_READ_SRC_REQ;
                    end
                end else begin
                    // The committed segment ended before the row boundary.
                    line_write_index <= line_write_index + segment_beats_reg;
                    segment_beat_index <= 16'd0;
                    state <= ST_LINE_WRITE_REQ;
                end
            end else if (req_fire) begin
                request_count <= request_count + 32'd1;
                if (mem_req_write) begin
                    write_count <= write_count + 32'd1;
                    // Fill and result writes complete a pixel.  A skipped
                    // COLOR_KEY pixel is accounted for in the response path.
                    if (last_pixel) begin
                        pixel_count <= pixel_count + 32'd1;
                        done_valid <= 1'b1;
                        done_error <= 1'b0;
                        done_seq <= seq_reg;
                        state <= ST_IDLE;
                    end else begin
                        pixel_count <= pixel_count + 32'd1;
                        x_reg <= next_x;
                        y_reg <= next_y;
                        cur_src_addr <= next_src_addr;
                        cur_dst_addr <= next_dst_addr;
                        if (op_reg == OP_SOLID_FILL_C)
                            state <= ST_FILL_WRITE;
                        else
                            state <= ST_READ_SRC_REQ;
                    end
                end else begin
                    read_count <= read_count + 32'd1;
                    if (state == ST_READ_SRC_REQ)
                        state <= ST_READ_SRC_WAIT;
                    else
                        state <= ST_READ_DST_WAIT;
                end
            end else if (rsp_fire) begin
                // The baseline issues one-beat reads, so a response without
                // `last` is a protocol error even when the data bus itself
                // reports no memory fault.
                if (mem_rsp_error || !mem_rsp_last) begin
                    done_valid <= 1'b1;
                    done_error <= 1'b1;
                    done_seq   <= seq_reg;
                    error_count <= error_count + 32'd1;
                    state <= ST_IDLE;
                end else if (state == ST_READ_SRC_WAIT) begin
                    src_pixel_reg <= mem_rsp_rdata;
                    if (WRITE_BURST_ENABLE) begin
                        if ((op_reg == OP_ALPHA_BLEND_C) ||
                            ((op_reg == OP_COLOR_KEY_C) &&
                             (mem_rsp_rdata[15:0] == color_key_reg))) begin
                            // ALPHA always needs the destination background;
                            // a COLOR_KEY hit reads it so a complete-row
                            // write-back preserves the original destination.
                            state <= ST_READ_DST_REQ;
                        end else begin
                            // BLOCK_COPY and COLOR_KEY misses can be deposited
                            // immediately into the line buffer.
                            pixel_count <= pixel_count + 32'd1;
                            if (x_reg == (width_reg - 16'd1)) begin
                                line_write_index <= 16'd0;
                                state <= ST_LINE_WRITE_REQ;
                            end else begin
                                x_reg <= next_x;
                                y_reg <= next_y;
                                cur_src_addr <= next_src_addr;
                                cur_dst_addr <= next_dst_addr;
                                state <= ST_READ_SRC_REQ;
                            end
                        end
                    end else if (op_reg == OP_ALPHA_BLEND_C) begin
                        state <= ST_READ_DST_REQ;
                    end else if ((op_reg == OP_COLOR_KEY_C) &&
                                 (mem_rsp_rdata[15:0] == color_key_reg)) begin
                        // Legacy path: color-key hit does not issue a write.
                        if (last_pixel) begin
                            pixel_count <= pixel_count + 32'd1;
                            done_valid <= 1'b1;
                            done_error <= 1'b0;
                            done_seq <= seq_reg;
                            state <= ST_IDLE;
                        end else begin
                            pixel_count <= pixel_count + 32'd1;
                            x_reg <= next_x;
                            y_reg <= next_y;
                            cur_src_addr <= next_src_addr;
                            cur_dst_addr <= next_dst_addr;
                            state <= ST_READ_SRC_REQ;
                        end
                    end else begin
                        state <= ST_WRITE_RESULT;
                    end
                end else begin
                    // Destination background response for ALPHA_BLEND, or
                    // preserved destination for a COLOR_KEY hit.
                    dst_pixel_reg <= mem_rsp_rdata;
                    if (WRITE_BURST_ENABLE) begin
                        pixel_count <= pixel_count + 32'd1;
                        if (x_reg == (width_reg - 16'd1)) begin
                            line_write_index <= 16'd0;
                            state <= ST_LINE_WRITE_REQ;
                        end else begin
                            x_reg <= next_x;
                            y_reg <= next_y;
                            cur_src_addr <= next_src_addr;
                            cur_dst_addr <= next_dst_addr;
                            state <= ST_READ_SRC_REQ;
                        end
                    end else begin
                        state <= ST_WRITE_RESULT;
                    end
                end
            end
        end
    end

`ifndef SYNTHESIS
    initial begin
        if (ADDR_W < 2 || DATA_W != 16 || LEN_W != 16 || SEQ_W <= 0)
            $error("render_cmd_mem_engine: first RTL version requires ADDR_W>=2, DATA_W=16 and LEN_W=16");
        if (MAX_WRITE_BEATS <= 0 || MAX_WRITE_BEATS > 65535)
            $error("render_cmd_mem_engine: MAX_WRITE_BEATS must be 1..65535");
        if (MAX_READ_BEATS <= 0 || MAX_READ_BEATS > 65535)
            $error("render_cmd_mem_engine: MAX_READ_BEATS must be 1..65535");
        if (READ_BURST_ENABLE && !WRITE_BURST_ENABLE)
            $error("render_cmd_mem_engine: READ_BURST_ENABLE requires WRITE_BURST_ENABLE");
        if (LINE_BUFFER_PIXELS <= 0 || LINE_BUFFER_PIXELS > 65535)
            $error("render_cmd_mem_engine: LINE_BUFFER_PIXELS must be 1..65535");
        if (READ_BOUNDARY_BYTES < (DATA_W/8) ||
            (READ_BOUNDARY_BYTES % (DATA_W/8)) != 0)
            $error("render_cmd_mem_engine: read boundary must contain an integer number of beats");
        if (WRITE_BOUNDARY_BYTES < (DATA_W/8) ||
            (WRITE_BOUNDARY_BYTES % (DATA_W/8)) != 0)
            $error("render_cmd_mem_engine: write boundary must contain an integer number of beats");
    end
`endif

